def send_email_notification(
    subject: str,
    body: str,
):
    """
    Send an email notification using SMTP configuration from
    environment variables.

    Required environment variables:
        SMTP_HOST
        SMTP_PORT
        SMTP_USERNAME
        SMTP_PASSWORD
        EMAIL_FROM
        EMAIL_TO

    Email failures are caught so they do not affect the experiment run.
    """

    smtp_host = os.getenv("SMTP_HOST")
    smtp_port = int(os.getenv("SMTP_PORT", "465"))
    smtp_username = os.getenv("SMTP_USERNAME")
    smtp_password = os.getenv("SMTP_PASSWORD")
    email_from = os.getenv("EMAIL_FROM")
    email_to = os.getenv("EMAIL_TO")

    required_values = {
        "SMTP_HOST": smtp_host,
        "SMTP_USERNAME": smtp_username,
        "SMTP_PASSWORD": smtp_password,
        "EMAIL_FROM": email_from,
        "EMAIL_TO": email_to,
    }

    missing = [
        key
        for key, value in required_values.items()
        if not value
    ]

    if missing:
        print(
            "\nEmail notification skipped. "
            "Missing environment variables: "
            + ", ".join(missing)
        )
        return

    message = EmailMessage()
    message["Subject"] = subject
    message["From"] = email_from
    message["To"] = email_to
    message.set_content(body)

    try:
        with smtplib.SMTP_SSL(
            smtp_host,
            smtp_port,
        ) as server:
            server.login(
                smtp_username,
                smtp_password,
            )
            server.send_message(message)

        print(
            f"\nEmail notification sent to: "
            f"{email_to}"
        )

    except Exception as exc:
        print(
            "\nEmail notification failed: "
            f"{exc}"
        )


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Generate MongoDB queries for questions "
            "contained in a CSV file."
        )
    )

    parser.add_argument(
        "input_csv",
        type=str,
        help="Input CSV file",
    )

    parser.add_argument(
        "--run-name",
        type=str,
        required=True,
        help=(
            "Name of the run. Results will be stored in "
            "output/<run-name>/"
        ),
    )

    parser.add_argument(
        "--model",
        type=str,
        default="ollama/llama3.1:8b",
        help="LiteLLM model name",
    )

    parser.add_argument(
        "--sample-size",
        type=int,
        default=100,
        help=(
            "Documents sampled per collection "
            "for schema inference"
        ),
    )

    args = parser.parse_args()

    try:
        process_csv(
            input_csv=args.input_csv,
            run_name=args.run_name,
            model=args.model,
            sample_size=args.sample_size,
        )

        send_email_notification(
            subject=(
                "Text-to-NoSQL run COMPLETED: "
                f"{args.run_name}"
            ),
            body=(
                f"Run name: {args.run_name}\n"
                f"Model: {args.model}\n"
                "Status: COMPLETED\n\n"
                "Details:\n"
                f"Results are available in "
                f"output/{args.run_name}/"
            ),
        )

    except Exception as exc:
        send_email_notification(
            subject=(
                "Text-to-NoSQL run FAILED: "
                f"{args.run_name}"
            ),
            body=(
                f"Run name: {args.run_name}\n"
                f"Model: {args.model}\n"
                "Status: FAILED\n\n"
                f"Error:\n{exc}"
            ),
        )

        raise


if __name__ == "__main__":
    main()